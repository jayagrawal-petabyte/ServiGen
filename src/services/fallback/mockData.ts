function buildStages(activeLabel: StageLabel): MajorIncident['lifecycleStages'] {
  const activeIndex = Math.max(0, STAGE_LABELS.indexOf(activeLabel));
  return STAGE_LABELS.map((label, idx) => ({
    label,
    isActive: idx === activeIndex,
    isCompleted: idx < activeIndex,
    timestamp: idx <= activeIndex ? new Date(Date.now() - (6 - idx) * 30 * 60 * 1000).toISOString() : undefined,
  }));
}

